#!/usr/bin/env python3
"""Copy the dashboard's light design tokens into the public pages' ``tokens.css``.

``packages/herdr-design-system/theme.css`` is the single source.  Only its first ``:root`` block (the light values) is
copied: the public side is light only, so the dark palette never ships there.  ``--check`` writes nothing and exits 1
when the generated file differs from the committed one.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "packages" / "herdr-design-system" / "theme.css"
TARGET = ROOT / "herdr_engineering" / "control_plane" / "share_static" / "tokens.css"
HEADER = ("/* Generated by scripts/sync_share_tokens.py from packages/herdr-design-system/theme.css: light tokens only.\n"
          " * Do not edit by hand; run the script (or --check in CI). */\n")


def render(theme_css: str) -> str:
    match = re.search(r"^:root\s*\{.*?^\}", theme_css, re.S | re.M)
    if match is None:
        raise SystemExit("no :root block in theme.css")
    return HEADER + match.group(0) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when the target is out of date; write nothing")
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--out", type=Path, default=TARGET)
    args = parser.parse_args(argv)
    wanted = render(args.source.read_text(encoding="utf-8"))
    current = args.out.read_text(encoding="utf-8") if args.out.is_file() else None
    if args.check:
        if current != wanted:
            print(f"{args.out} is out of date; run scripts/sync_share_tokens.py", file=sys.stderr)
            return 1
        return 0
    if current != wanted:
        args.out.write_text(wanted, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
