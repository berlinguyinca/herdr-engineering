#!/usr/bin/env node
// Generates docs/dashboard-sitemap.json and docs/dashboard-sitemap.md from the dashboard's own route table.
//
//   node scripts/gen-dashboard-sitemap.mjs           write both files
//   node scripts/gen-dashboard-sitemap.mjs --check   exit 1 if the committed files differ from what the code says now
//
// READ from packages/app.js: ROUTES (route -> view function), NAV (sidebar group/label/capability/owned paths), SECTION_TABS (tab strips)
// and the query parameters each view function reads. KEPT in tests/playwright/dashboard-routes.mjs: titles, parameter examples, sub-views,
// proof selectors, fixture status. Output is deterministic (no timestamps), so a diff means the code or the notes changed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const APP = path.join(ROOT, 'packages', 'app.js');

/** The text of a top-level `const NAME = <open> ... \n<close>;` block of app.js (the closing bracket sits alone at the start of a line). */
function block(src, name, open, close) {
  const start = src.indexOf(`const ${name} = ${open}`);
  if (start < 0) throw new Error(`app.js has no "const ${name}" block`);
  const from = src.indexOf(open, start);
  const end = src.indexOf(`\n${close};`, from);
  return src.slice(from, end + 2);
}
const evalLiteral = (text) => new Function(`return (${text})`)();   // our own checked-in source, never user input

export function readRouteTable(src = fs.readFileSync(APP, 'utf8')) {
  const nav = evalLiteral(block(src, 'NAV', '[', ']'));
  const tabs = evalLiteral(block(src, 'SECTION_TABS', '[', ']'));
  const routesText = src.slice(src.indexOf('const ROUTES = {'), src.indexOf('\n};', src.indexOf('const ROUTES = {')));
  const routes = [...routesText.matchAll(/^\s*'([^']+)':\s*(\w+),?\s*$/gm)].map(([, route, view]) => ({ route, view }));
  if (!routes.length) throw new Error('app.js ROUTES block not found');
  // query parameters: every query.get('x') / q.get('x') / route().query.get('x') inside the view function's body
  const bodies = new Map();
  const fnRe = /^(?:async )?function (\w+)\(/gm;
  const starts = [...src.matchAll(fnRe)].map((m) => ({ name: m[1], at: m.index }));
  starts.forEach((s, i) => bodies.set(s.name, src.slice(s.at, i + 1 < starts.length ? starts[i + 1].at : src.length)));
  const queryOf = (view) => [...new Set([...(bodies.get(view) || '').matchAll(/(?:\bquery|\bq|route\(\)\.query)\.get\('(\w+)'\)/g)].map((m) => m[1]))].sort();
  return { nav, tabs, routes, queryOf };
}

const segMatch = (route, owned) => route === owned || route.startsWith(owned + '/');

export function buildSitemap({ notes, src } = {}) {
  const { nav, tabs, routes, queryOf } = readRouteTable(src);
  const entries = routes.map(({ route, view }) => {
    const owners = nav.filter((e) => [e.path, ...(e.match || [])].some((p) => segMatch(route.replace(/\/:.*$/, ''), p) || segMatch(route, p)));
    const owner = owners.sort((a, b) => Math.max(...[b.path, ...(b.match || [])].map((p) => p.length)) - Math.max(...[a.path, ...(a.match || [])].map((p) => p.length)))[0];
    const own = nav.find((e) => e.path === route);
    const tabRow = tabs.find((row) => row.some(([p]) => p === route));
    const n = notes[route] || {};
    const params = [...route.matchAll(/:(\w+)/g)].map((m) => m[1]);
    const example = params.length ? route.replace(/:(\w+)/g, (_, p) => n.params?.[p]?.example ?? `<${p}>`) : route;
    const query = Object.fromEntries(queryOf(view).map((k) => [k, n.query?.[k] || (n.subviews ? 'sub-view selector (see subviews)' : '')]));
    return {
      route, hash: `#${example}`, title: n.title || '', view,
      nav: owner ? { group: owner.group, label: owner.label, entry: owner.path, listedInSidebar: !!own, capability: owner.capability || null } : null,
      sectionTabs: tabRow ? { label: tabRow.find(([p]) => p === route)[1], siblings: tabRow.map(([p]) => p) } : null,
      params: Object.fromEntries(params.map((p) => [p, n.params?.[p] || { example: '', how: '' }])),
      query,
      subviews: n.subviews || [],
      fixture: n.fixture || { status: 'pending', reason: '' },
      proof: n.proof || '',
      surfaces: n.surfaces || [],
      ...(n.note ? { note: n.note } : {}),
    };
  });
  return { generatedFrom: 'packages/app.js + tests/playwright/dashboard-routes.mjs', routeCount: entries.length, surfaceCount: entries.reduce((a, e) => a + e.surfaces.length, 0),
    navGroups: [...new Set(nav.map((e) => e.group))], routes: entries };
}

export function renderMarkdown(map) {
  const out = ['# Dashboard sitemap', '',
    'Generated by `node scripts/gen-dashboard-sitemap.mjs` from `packages/app.js` (route table, sidebar, tab strips, query parameters) and',
    '`tests/playwright/dashboard-routes.mjs` (titles, parameter examples, sub-views, proof selectors, fixture status). Do not edit by hand:',
    '`packages/dashboard-sitemap.test.js` fails when this file, `docs/dashboard-sitemap.json` and the code disagree. Machine-readable twin: `docs/dashboard-sitemap.json`.', '',
    `${map.routeCount} routes, ${map.surfaceCount} capture surfaces. Open any route at \`<origin>/index.html<hash>\`.`, ''];
  const by = {};
  for (const r of map.routes) (by[r.nav?.group || 'Unlisted'] ||= []).push(r);
  for (const group of [...map.navGroups, 'Unlisted'].filter((g) => by[g])) {
    const rows = by[group];
    out.push(`## ${group}`, '', '| Route | Hash to open | Title | Nav | Sub-views / query | Params | Fixture | Proof selector |', '|---|---|---|---|---|---|---|---|');
    for (const r of rows) {
      const nav = r.nav ? `${r.nav.label}${r.nav.listedInSidebar ? '' : ' (tab/linked)'}${r.nav.capability ? ` [needs ${r.nav.capability}]` : ''}` : '';
      const sub = [...r.subviews.map((s) => s.label), ...Object.keys(r.query).map((q) => `?${q}`)].join(', ');
      const params = Object.entries(r.params).map(([k, v]) => `${k}=${v.example}`).join(', ');
      out.push(`| \`${r.route}\` | \`${r.hash}\` | ${r.title} | ${nav} | ${sub} | ${params} | ${r.fixture.status}${r.fixture.reason ? `: ${r.fixture.reason}` : ''} | \`${r.proof}\` |`);
    }
    out.push('');
  }
  out.push('## Dynamic routes: how to instantiate', '');
  for (const r of map.routes.filter((x) => Object.keys(x.params).length)) out.push(`- \`${r.route}\`: ${Object.entries(r.params).map(([k, v]) => `\`${k}\` = \`${v.example}\` (${v.how})`).join('; ')}`);
  out.push('');
  return out.join('\n');
}

export async function generate() {
  const { ROUTE_NOTES } = await import(path.join(ROOT, 'tests', 'playwright', 'dashboard-routes.mjs'));
  const map = buildSitemap({ notes: ROUTE_NOTES });
  return { json: JSON.stringify(map, null, 2) + '\n', md: renderMarkdown(map), map };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { json, md } = await generate();
  const files = [[path.join(ROOT, 'docs', 'dashboard-sitemap.json'), json], [path.join(ROOT, 'docs', 'dashboard-sitemap.md'), md]];
  if (process.argv.includes('--check')) {
    const stale = files.filter(([f, text]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== text).map(([f]) => path.relative(ROOT, f));
    if (stale.length) { console.error(`stale: ${stale.join(', ')} (run node scripts/gen-dashboard-sitemap.mjs)`); process.exit(1); }
    console.log('dashboard sitemap is up to date');
  } else for (const [f, text] of files) { fs.writeFileSync(f, text); console.log('wrote', path.relative(ROOT, f)); }
}
